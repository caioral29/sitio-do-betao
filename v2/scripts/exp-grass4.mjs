import puppeteer from 'puppeteer-core';
const OUT = process.argv[2];
const browser = await puppeteer.launch({ executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: 'new', args: ['--use-angle=metal', '--enable-gpu', '--ignore-gpu-blocklist'] });
const page = await browser.newPage();
await page.setViewport({ width: 500, height: 300 });
await page.goto('http://localhost:5190/?hq', { waitUntil: 'load' });
await page.waitForSelector('#title.ready', { timeout: 120000 });
await page.click('#play');
const wait = (ms) => new Promise((r) => setTimeout(r, ms));
await wait(2000);
await page.evaluate(() => { const g = window.__game; g.player.pos.set(-1, 0, 3); g.rig.pitch = 0.16; g.rig.yaw = 1.45; g.rig.dist = 12; g.rig.autoYaw = null; g.setHour(17.9); });
await wait(900);
const names = await page.evaluate(() => window.__game.composer.passes.map((p) => p.name + ':' + (p.effects ? p.effects.map((e) => e.name).join(',') : '')));
console.log(names.join(' | '));
await page.evaluate(() => { const p = window.__game.composer.passes; p[1].enabled = false; });
await wait(300); await page.screenshot({ path: `${OUT}/a-noAO.png` });
await page.evaluate(() => { const p = window.__game.composer.passes; p[1].enabled = true; p[2].enabled = false; });
await wait(300); await page.screenshot({ path: `${OUT}/b-noFX.png` });
await page.evaluate(() => { const p = window.__game.composer.passes; p[2].enabled = true; p[3].enabled = false; });
await wait(300); await page.screenshot({ path: `${OUT}/c-noSMAA.png` });
await browser.close();
