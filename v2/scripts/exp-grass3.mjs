import puppeteer from 'puppeteer-core';
const OUT = process.argv[2];
const browser = await puppeteer.launch({ executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: 'new', args: ['--use-angle=metal', '--enable-gpu', '--ignore-gpu-blocklist'] });
const page = await browser.newPage();
await page.setViewport({ width: 500, height: 300 });
await page.goto('http://localhost:5190/?hq', { waitUntil: 'load' });
await page.waitForSelector('#title.ready', { timeout: 120000 });
await page.click('#play');
const wait = (ms) => new Promise((r) => setTimeout(r, ms));
await wait(2000);
await page.evaluate(() => { const g = window.__game; g.player.pos.set(-1, 0, 3); g.rig.pitch = 0.16; g.rig.yaw = 1.45; g.rig.dist = 12; g.rig.autoYaw = null; g.setHour(17.9); });
await wait(900);
const grass = `(() => { let gm; window.__game.scene.traverse((o) => { if (o.isInstancedMesh && o.count > 5000) gm = o; }); return gm; })()`;
await page.screenshot({ path: `${OUT}/0-base.png` });
await page.evaluate(() => { window.__game.renderer.render(window.__game.scene, window.__game.camera); });
await page.evaluate(() => { const g = window.__game; g._raw = true; const orig = g.composer.render.bind(g.composer); g.composer.render = () => g.renderer.render(g.scene, g.camera); });
await wait(300);
await page.screenshot({ path: `${OUT}/1-nopost.png` });
await page.evaluate(`(() => { const gm = ${grass}; gm.material.roughness = 1; gm.material.metalness = 0; gm.material.envMapIntensity = 0; gm.material.needsUpdate = true; })()`);
await wait(300);
await page.screenshot({ path: `${OUT}/2-noenv.png` });
const vals = await page.evaluate(() => { const g = window.__game; return { sunDir: g.sky.sun.position.clone().sub(g.sky.sun.target.position).normalize().toArray().map((v) => +v.toFixed(3)), sunColor: g.sky.sun.color.toArray(), cam: g.camera.position.toArray().map((v) => +v.toFixed(2)) }; });
console.log(JSON.stringify(vals));
await browser.close();
